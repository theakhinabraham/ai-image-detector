"""Generate the results tables from reports/*.json (no number is typed by hand).

Run:  python -I scripts/report_tables.py
Writes reports/results.md and replaces the block between the RESULTS markers in README.md.
A model whose JSON file does not exist is shown as "not run".
"""
from __future__ import annotations

import json
from pathlib import Path

R = Path("reports")
MODELS = ["smallcnn", "resnet18"]
NA = "not run"


def load(name: str) -> dict | None:
    p = R / name
    return json.loads(p.read_text()) if p.exists() else None


def f(x, digits=4) -> str:
    return NA if x is None else f"{x:.{digits}f}"


def table(header: list[str], rows: list[list[str]]) -> str:
    lines = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    lines += ["| " + " | ".join(r) + " |" for r in rows]
    return "\n".join(lines)


def main_comparison() -> str:
    rows = []
    for m in MODELS:
        met, tr = load(f"metrics_{m}.json"), load(f"train_{m}.json")
        if not met:
            rows.append([m] + [NA] * 8)
            continue
        rows.append([m, f"{met['input_size']}x{met['input_size']}", f(met["accuracy"]), f(met["f1"]),
                     f(met["roc_auc"]), f"{met['parameters']:,}", f(met["cpu_ms_per_image"], 2),
                     tr["device"] if tr else NA,
                     f"{tr['mean_seconds_per_epoch']:.0f} s x {tr['epochs_run']}" if tr else NA])
    return table(["Model", "Input", "Accuracy", "F1", "ROC-AUC", "Parameters", "CPU ms/image",
                  "Trained on", "Time/epoch x epochs"], rows)


def calibration() -> str:
    rows = []
    for m in MODELS + [x + "_mix" for x in MODELS]:
        c = load(f"calibration_{m}.json")
        if c:
            rows.append([m, f(c["temperature"], 3), f(c["test_ece_before"]), f(c["test_ece_after"]),
                         f(c["test_nll_before"]), f(c["test_nll_after"])])
    return table(["Model", "Temperature T", "ECE before", "ECE after", "NLL before", "NLL after"], rows)


def robustness() -> str:
    data = {m: load(f"robustness_{m}.json") for m in MODELS}
    names = next((list(d["results"]) for d in data.values() if d), [])
    rows = []
    for n in names:
        row = [n]
        for m in MODELS:
            r = data[m]["results"][n] if data[m] else None
            row += [f(r["accuracy"]) if r else NA, f(r["roc_auc"]) if r else NA]
        rows.append(row)
    header = ["Degradation"] + [f"{m} {k}" for m in MODELS for k in ("acc", "AUC")]
    return table(header, rows)


def cross_generator() -> str:
    runs = [r for r in MODELS + [m + "_mix" for m in MODELS] if load(f"cocoai_{r}.json")]
    if not runs:
        return "_COCOAI evaluation not run._"
    data = {r: load(f"cocoai_{r}.json") for r in runs}
    gens = list(next(iter(data.values()))["per_generator"])
    rows = [["CIFAKE test (in-distribution)"] +
            [f((load(f"metrics_{r}.json") or {}).get("roc_auc")) for r in runs]]
    rows.append(["COCOAI overall"] + [f(data[r]["overall"]["roc_auc"]) for r in runs])
    for g in gens:
        rows.append([f"COCOAI real vs {g}"] + [f(data[r]["per_generator"][g]["roc_auc"]) for r in runs])
    rows.append(["COCOAI accuracy (overall)"] + [f(data[r]["overall"]["accuracy"]) for r in runs])
    rows.append(["COCOAI real photos called real"] + [f(data[r]["real_photos_correct"]) for r in runs])
    return table(["ROC-AUC unless stated"] + runs, rows)


def build() -> str:
    return "\n\n".join([
        "### CIFAKE test set (20,000 images, never used for training or tuning)", main_comparison(),
        "CPU ms/image: batch of 1 on this laptop's CPU, mean of 200 runs after warm-up.",
        "### Calibration (T fitted on validation, reported on CIFAKE test)", calibration(),
        "### Robustness (CIFAKE test after degradation)", robustness(),
        "### Cross-generator generalisation (COCOAI held-out split: 1,000 real + 1,000 per generator)",
        cross_generator(),
        "`_mix` = fine-tuned on CIFAKE + COCOAI fine-tuning split (different captions from the test split).",
    ])


def main() -> None:
    text = build()
    (R / "results.md").write_text("# Results (generated by scripts/report_tables.py)\n\n" + text + "\n")
    readme = Path("README.md")
    start, end = "<!-- RESULTS START -->", "<!-- RESULTS END -->"
    s = readme.read_text()
    if start in s and end in s:
        s = s[: s.index(start) + len(start)] + "\n" + text + "\n" + s[s.index(end):]
        readme.write_text(s)
    print(text)


if __name__ == "__main__":
    main()
